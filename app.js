function getInitialLang() {
  const params = new URLSearchParams(window.location.search);
  const queryLang = params.get("lang");
  if (queryLang === "en" || queryLang === "ar") {
    return queryLang;
  }
  try {
    const saved = window.localStorage.getItem("kitabi_lang");
    if (saved === "en" || saved === "ar") {
      return saved;
    }
  } catch {
    // Ignore storage errors in restricted contexts.
  }
  return "ar";
}

function applyLanguage(lang, persist = true) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.ar;
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";

  document.title = dict.pageTitle;
  const descMeta = document.querySelector('meta[name="description"]');
  if (descMeta) {
    descMeta.setAttribute("content", dict.pageDescription);
  }

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (key && Object.prototype.hasOwnProperty.call(dict, key)) {
      el.setAttribute("alt", dict[key]);
    }
  });

  const langBtn = document.getElementById("lang-toggle");
  const langLabel = document.getElementById("lang-toggle-label");
  if (langBtn && langLabel) {
    langLabel.textContent = dict.langButton;
    langBtn.setAttribute("aria-label", dict.langButtonAria);
    langBtn.setAttribute("lang", lang === "ar" ? "en" : "ar");
  }

  if (persist) {
    try {
      window.localStorage.setItem("kitabi_lang", lang);
    } catch {
      // Ignore storage errors.
    }
  }
}

document.addEventListener("DOMContentLoaded", () => {
  let currentLang = getInitialLang();
  applyLanguage(currentLang, false);

  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) {
    langBtn.addEventListener("click", () => {
      currentLang = currentLang === "ar" ? "en" : "ar";
      applyLanguage(currentLang, true);
    });
  }

  const yearEl = document.getElementById("year");
  if (yearEl) {
    yearEl.textContent = String(new Date().getFullYear());
  }

  const dialog = document.getElementById("image-dialog");
  const dialogImg = document.getElementById("lightbox-img");
  const closeBtn = document.getElementById("lightbox-close");

  document.querySelectorAll("[data-lightbox-src]").forEach((btn) => {
    btn.addEventListener("click", () => {
      if (!dialog || !dialogImg) return;
      dialogImg.src = btn.getAttribute("data-lightbox-src") || "";
      const imgChild = btn.querySelector("img");
      dialogImg.alt = imgChild ? imgChild.alt : "";
      dialog.showModal();
    });
  });

  if (closeBtn && dialog) {
    closeBtn.addEventListener("click", () => dialog.close());
    dialog.addEventListener("click", (event) => {
      if (event.target === dialog) {
        dialog.close();
      }
    });
  }
});
